"""
Read eval result JSON files (generated by eval_peft_adapter.py or eval_base_model.py)
and plot the key metrics for quick comparison.

Usage:
  python src/evals/plot_eval_results.py \
    --inputs src/evals/results/base_gpt2_metrics.json src/evals/results/gpt2_eval.json \
    --output-dir src/evals/results/plots

Creates bar charts for:
  - Wikitext loss and perplexity
  - IMDB accuracy
  - SST2 accuracy
  - SQuAD exact match
"""

import argparse
import json
from pathlib import Path
from typing import Dict, List

import matplotlib.pyplot as plt


def load_results(paths: List[Path]) -> Dict[str, Dict]:
    results = {}
    for p in paths:
        with p.open() as f:
            results[p.stem] = json.load(f)
    return results


def plot_bar(metric_name: str, values: Dict[str, float], ylabel: str, output_dir: Path):
    labels = list(values.keys())
    data = [values[k] for k in labels]
    plt.figure(figsize=(8, 4))
    plt.bar(labels, data)
    plt.title(metric_name)
    plt.ylabel(ylabel)
    plt.xticks(rotation=20, ha="right")
    plt.tight_layout()
    output_path = output_dir / f"{metric_name.replace(' ', '_').lower()}.png"
    plt.savefig(output_path, dpi=200)
    plt.close()
    print(f"Saved {output_path}")


def main():
    parser = argparse.ArgumentParser(description="Plot eval metrics from JSON files.")
    parser.add_argument("--inputs", nargs="+", required=True, help="List of eval JSON files.")
    parser.add_argument("--output-dir", default="src/evals/results/plots")
    args = parser.parse_args()

    input_paths = [Path(p) for p in args.inputs]
    for p in input_paths:
        if not p.exists():
            raise FileNotFoundError(f"Input file not found: {p}")

    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    results = load_results(input_paths)

    # Collect metrics
    metrics = {
        "Wikitext Loss": {name: r.get("wikitext", {}).get("loss") for name, r in results.items()},
        "Wikitext Perplexity": {name: r.get("wikitext", {}).get("perplexity") for name, r in results.items()},
        "IMDB Accuracy": {name: r.get("imdb", {}).get("accuracy") for name, r in results.items()},
        "SST2 Accuracy": {name: r.get("sst2", {}).get("accuracy") for name, r in results.items()},
        "SQuAD Exact Match": {name: r.get("squad", {}).get("exact_match") for name, r in results.items()},
    }

    for metric_name, vals in metrics.items():
        # Drop missing values
        filtered = {k: v for k, v in vals.items() if v is not None}
        if not filtered:
            continue
        plot_bar(metric_name, filtered, metric_name, output_dir)


if __name__ == "__main__":
    main()
